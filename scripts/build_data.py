"""Build all WP-A data: cleaned split texts, evaluation passages, Visual-BPE dictionaries.

    python3 scripts/build_data.py            # build whatever is missing
    python3 scripts/build_data.py --force    # rebuild everything
    python3 scripts/build_data.py --report   # also (re)write docs/glyphs/dictionary-report.md (K1)

Outputs (data/, git-ignored): train.txt val.txt test.txt, passages_{natural,scrambled}.jsonl,
dict_3000.json (master) and its prefixes dict_{100,300,1000}.json.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from vbpe import config, corpus, dictionary  # noqa: E402
from vbpe.layout import Unit, fit_em  # noqa: E402

SIZES = (100, 300, 1000, 3000)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="rebuild even if cached")
    ap.add_argument("--report", action="store_true", help="write docs/glyphs/dictionary-report.md")
    args = ap.parse_args()
    config.DATA.mkdir(parents=True, exist_ok=True)

    for split in ("test", "val", "train"):
        p = corpus.split_path(split)
        if args.force or not p.exists():
            print(f"building {p} ...", flush=True)
            corpus.build_split(split)
        print(f"{p}: {p.stat().st_size:,} bytes")

    if args.force or not all((config.DATA / f"passages_{v}.jsonl").exists()
                             for v in ("natural", "scrambled")):
        corpus.build_passages()
    for v in ("natural", "scrambled"):
        ps = corpus.load_passages(v)
        print(f"passages_{v}: {len(ps)} passages, lengths {[len(p['text']) for p in ps]}")

    master_p = dictionary.dict_path(dictionary.MASTER_N)
    if args.force or not master_p.exists():
        master = dictionary.build(dictionary.MASTER_N)
    else:
        master = dictionary.Dictionary.from_file(master_p)
    for n in SIZES:
        if n != dictionary.MASTER_N:
            master.prefix(n).save(dictionary.dict_path(n))
        print(f"dict_{n}.json: first tokens {master.tokens[:min(n, 8)]}")
    if args.report:
        write_report(master)


class _Box(Unit):
    """Placeholder unit with a fixed em width (layout check without a real glyph scheme)."""

    def __init__(self, source: str, width_em: float):
        self.source, self.labels, self.w = source, (source,), width_em
        self.is_space = source.isspace()

    def advance(self, em: float) -> float:
        return self.w * em

    def draw(self, d, x, baseline, em) -> None:  # pragma: no cover - never drawn
        pass


def _fit_ratio(d: dictionary.Dictionary, text: str, W: int = 768, H: int = 768) -> float:
    """em(subst) / em(condensed) when a passage is fitted to a W x H page by vbpe.layout."""
    cond = [_Box(c, d.char_width(c)) for c in text]
    sub = [_Box(s, d.segment_width(s)) for s in d.segment(text)]
    return fit_em(sub, W, H) / fit_em(cond, W, H)


def write_report(master: dictionary.Dictionary, path: Path = config.ROOT / "docs" / "glyphs" / "dictionary-report.md") -> None:
    val = corpus.read_paragraphs("val")
    rows, stats = [], {}
    for n in SIZES:
        d = master.prefix(n)
        st = dictionary.k1_stats(d, val)
        stats[n] = st
        nat = corpus.load_passages("natural")
        fr = [_fit_ratio(d, p["text"]) for p in nat]
        rows.append(
            f"| {n} | {st['seg_ratio']:.3f} | {st['ratio_vs_condensed']:.3f} | "
            f"{1 - st['ratio_vs_condensed']:.1%} | {st['ratio_vs_latin']:.3f} | {st['coverage']:.1%} | "
            f"{st['em_gain_vs_condensed']:.3f} | {st['em_gain_vs_latin']:.3f} | "
            f"{sum(fr) / len(fr):.3f} | {st['unused_tokens']} |")
        print(rows[-1], flush=True)
    s1000 = stats[1000]
    k1_pass = 1 - s1000["ratio_vs_condensed"] >= 0.15
    cond_vs_lat = s1000["width_condensed"] / s1000["width_latin"]
    use1000 = stats[1000]["token_use"]
    d1000 = master.prefix(1000)
    est = master.meta.get("est_gain_em", [])
    top = []
    for i, t in enumerate(master.tokens[:40]):
        sav = d1000.token_saving(t)
        top.append(f"| {i} | `{t.replace(' ', '\u2423')}` | {len(t)} | {d1000.latin_width(t):.3f} | {sav:.3f} | "
                   f"{est[i] if i < len(est) else float('nan'):,.0f} | {use1000[t]:,} | {use1000[t] * sav:,.0f} |")
    m = master.meta
    md = f"""# Visual-BPE dictionary report (WP-A, kill check K1)

Generated by `python3 scripts/build_data.py --report`. Dictionary files: `data/dict_{{100,300,1000,3000}}.json`
(smaller N = prefixes of the 3000-token master, so experiments are nested).

## Verdict

**K1 {"PASSES" if k1_pass else "FAILS"}.** At N = 1000 the substitution encoding is
**{1 - s1000["ratio_vs_condensed"]:.1%} narrower** than condensed Latin (Archivo Narrow) at equal em on held-out
WikiText-103 validation text (bar: >= 15 %). Width ratio {s1000["ratio_vs_condensed"]:.3f}; implied max em gain for a fixed
page sqrt(1/ratio) = {s1000["em_gain_vs_condensed"]:.3f}x. (Condensed Latin itself is {cond_vs_lat:.3f}x the width of DejaVu Sans.)

This is only the *analytic* precondition: it assumes a 1.0 em symbol is as legible as a Latin letter at the
same em, which is exactly what Phases 1-2 test (PLAN R3).

## K1 table (held-out val text, {s1000["chars"]:,} chars, equal em)

Columns: (a) segments / source chars; (b) rendered width vs condensed Latin (leftovers in Archivo Narrow +
1.0 em per symbol) and the resulting line-width saving; (c) width vs DejaVu Sans Latin; (d) fraction of source
chars covered by tokens; implied max em gain on a fixed page = sqrt(1 / width ratio) vs condensed / vs DejaVu;
"layout em gain" = em(subst) / em(condensed) actually found by `vbpe.layout.fit_em` for the 12 natural
passages on a 768x768 page (includes line-breaking and line-quantisation effects); unused = tokens never
used on val.

| N | (a) seg/char | (b) width vs condensed | saving | (c) width vs DejaVu | (d) coverage | em gain vs cond | em gain vs DejaVu | layout em gain (768²) | unused |
|---|---|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

## How the dictionary was built

* Widths: per-glyph advances of `{Path(master.font_path).name}` measured with PIL at 1000 px / 1000 (layout draws
  one glyph per char, no kerning). Mean ~0.37 em/char on text; space = {d1000.char_width(' '):.3f} em. A token saves
  `width_em(t) - 1.0` per use, so only chains wider than 1 em are candidates (2-char tokens qualify only for wide
  letters, e.g. `ma`, `me`).
* Sample: {m.get("sample_chars", 0):,} chars of random paragraphs from the cleaned train text (seed {m.get("sample_seed")}).
* Candidates: all substrings of length 2..{m.get("max_len")} (spaces allowed, never crossing paragraphs) with
  width > 1 em, count >= {m.get("min_count")} and count*(w-1) >= {dictionary.MIN_POTENTIAL:g} em: {m.get("n_candidates", 0):,} candidates
  (64-bit rolling hashes + `np.unique`).
* Greedy batch selection with re-segmentation (handles overlap): each round segments the whole sample by the
  exact min-width DP with the current dictionary, then scores every candidate by
  sum over its occurrences whose two ends fall on current segment boundaries of (current width of that span - 1 em).
  Chars already inside tokens are therefore not double counted, and a longer chain (e.g. `␣of␣the␣`) only gets
  credit for what it saves beyond the tokens already covering it. The top-k are added (k = 8 per round until
  100 tokens, then 8 % of the current size), skipping candidates that are sub/super-strings of or overlap
  (>= 2 chars) one already picked in the same round. Selection order = priority order (`tokens[i]` -> i-th symbol).
* Build time {m.get("build_seconds")} s; final width ratio on the train sample {m.get("sample_width_ratio", 0):.4f} (val: {stats[3000]["ratio_vs_condensed"]:.4f} -> no overfitting).
* `Dictionary.segment` is an exact DP minimising rendered width; a token is used only if it strictly saves width,
  so the encoding is never wider than plain condensed Latin.

## Top 40 tokens (priority order; `␣` = space)

Saving = em saved per occurrence; est. gain = marginal gain (em) on the train sample when it was selected;
val uses / em saved measured with the N = 1000 dictionary.

| # | token | len | width em (condensed) | saving/use | est. gain (train) | val uses (N=1000) | val em saved |
|---|---|---|---|---|---|---|---|
{chr(10).join(top)}

## Caveats for downstream

* Tokens may contain internal spaces (`n␣the␣`), which removes line-break opportunities inside them; the
  layout em-gain column already includes that effect.
* Equal-em comparison assumes the symbol fits the same 1.0 em x line-pitch box as Latin; CJK ideographs are full
  height, so their legibility per pixel is the open question for Phases 1-2.
* Case-sensitive: `The␣` and `the␣` are different tokens.
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(md)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
