"""Analysis of results/compaction_scale/runs.jsonl -> summary.md / summary.json (pre-registration in README.md).

Accuracy per arm (pooled, per session kind, per turn, task items); paired differences (Newcombe 95% interval, exact
McNemar) for B - A, B - D, A - D; costs after the shared reading step.

Cost accounting: A and B compact the same history, but A's fork and /compact ran first and left that history in the
prompt cache, so B's fork and /compact were billed mostly as cache reads (~10x cheaper). That is an artefact of the
order, not of the hooks, so both arms are charged A's (cold-cache) fork + compaction cost. The hooks add no model
calls; their render time is reported separately.
"""
from __future__ import annotations

import json
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments"))
from analyse_claude_qa import mcnemar, paired_diff_ci  # noqa: E402

OUT = ROOT / "results" / "compaction_scale"
ARMS = {"D": "no compaction", "A": "normal compaction", "B": "compaction + page archive (hooks)"}


def main() -> int:
    rows = {}
    for l in (OUT / "runs.jsonl").read_text().splitlines():
        r = json.loads(l)
        rows[(r["session"], r["arm"], r["step"])] = r                 # a later row wins
    sessions = sorted({s for s, a, t in rows if all((s, x, "task") in rows for x in ARMS)})
    kind = {s: s.split(":")[0] for s in sessions}
    per = defaultdict(dict)                                           # (arm) -> {(session, qid): correct}
    task = defaultdict(dict)
    turn_acc = defaultdict(lambda: defaultdict(list))
    ans_cost = defaultdict(lambda: defaultdict(float))
    reads = defaultdict(lambda: defaultdict(int))
    for (s, a, t), r in rows.items():
        if s not in sessions or a not in ARMS or not (t.startswith("turn") or t == "task"):
            continue
        for p in r["scores"]:
            (task if t == "task" else per)[a][(s, p["id"], p["kind"])] = p["correct"]
            if t != "task":
                turn_acc[a][t].append(p["correct"])
        ans_cost[a][s] += r["cost"]
        reads[a]["archive"] += r.get("archive_reads", 0)
        reads[a]["transcript"] += r.get("transcript_reads", 0)
        reads[a]["all"] += r["reads"]
    comp = {s: rows[(s, "A", "fork")]["cost"] + rows[(s, "A", "compact")]["cost"] for s in sessions}
    read = {s: rows[(s, "-", "read")]["cost"] for s in sessions}
    keys = sorted(per["D"])
    acc = lambda a, ks: sum(per[a][k] for k in ks) / len(ks)          # noqa: E731
    S = {"sessions": sessions, "n_questions": len(keys), "arms": {}}
    L = ["# Compaction archive at scale: results", "", "Generated by `experiments/compaction/analyse_scale.py`. "
         f"{len(sessions)} sessions ({', '.join(sessions)}), {len(keys)} questions + "
         f"{len(task['D'])} task items per arm.", "",
         "| arm | questions right | research | code | logs | task items | compaction $ | answering $ | after reading $ | "
         "$ per correct answer | archive pages opened | transcript (JSONL) reads |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for a, lab in ARMS.items():
        by_kind = {k: acc(a, [x for x in keys if kind[x[0]] == k]) for k in ("research", "code", "logs")
                   if any(kind[x[0]] == k for x in keys)}
        tk = sum(task[a].values()) / len(task[a])
        c_comp = sum(comp.values()) if a != "D" else 0.0
        c_ans = sum(ans_cost[a].values())
        n_ok = sum(per[a][k] for k in keys) + sum(task[a].values())
        x = {"acc": acc(a, keys), "by_kind": by_kind, "task": tk, "compaction_cost": c_comp, "answer_cost": c_ans,
             "after_reading_cost": c_comp + c_ans, "cost_per_correct": (c_comp + c_ans) / max(1, n_ok),
             "answer_cost_per_correct": c_ans / max(1, n_ok), "reads": dict(reads[a]),
             "per_turn": {t: st.mean(v) for t, v in sorted(turn_acc[a].items())},
             "per_session": {s: {"acc": acc(a, [k for k in keys if k[0] == s]), "answer_cost": ans_cost[a][s]}
                             for s in sessions}}
        S["arms"][a] = x
        L.append(f"| {lab} | {100 * x['acc']:.1f}% | " + " | ".join(f"{100 * by_kind.get(k, 0):.1f}%" for k in
                 ("research", "code", "logs")) + f" | {100 * tk:.0f}% | ${c_comp:.2f} | ${c_ans:.2f} | "
                 f"${x['after_reading_cost']:.2f} | ${x['cost_per_correct']:.4f} | {reads[a]['archive']} | "
                 f"{reads[a]['transcript']} |")
    L += ["", f"Shared by all arms: reading ${sum(read.values()):.2f} in total. Compaction is charged at A's cold-cache "
          "cost to both A and B (see the module docstring).", ""]
    L += ["Accuracy by turn (10 questions each):", "", "| arm | " + " | ".join(sorted(turn_acc["D"])) + " |",
          "|---|" + "---|" * len(turn_acc["D"])]
    for a, lab in ARMS.items():
        L.append(f"| {lab} | " + " | ".join(f"{100 * v:.0f}%" for _, v in sorted(S['arms'][a]['per_turn'].items())) + " |")
    L += ["", "Paired differences over all questions (95% CI, exact McNemar):", ""]
    S["diffs"] = {}
    for x, y in (("B", "A"), ("B", "D"), ("A", "D")):
        pairs = [("q", per[y][k], per[x][k]) for k in keys]
        d, lo, hi = paired_diff_ci(pairs)
        _, _, p = mcnemar([t for _, t, _ in pairs], [i for _, _, i in pairs])
        S["diffs"][f"{x}-{y}"] = {"diff": -d, "lo": -hi, "hi": -lo, "p": p}
        L.append(f"* {x} - {y}: {-100 * d:+.1f} points ({-100 * hi:+.1f} to {-100 * lo:+.1f}), p = {p:.2g}")
    tpairs = [("t", task["A"][k], task["B"][k]) for k in sorted(task["A"])]
    d, lo, hi = paired_diff_ci(tpairs)
    S["diffs"]["task B-A"] = {"diff": -d, "lo": -hi, "hi": -lo}
    L.append(f"* task items, B - A: {-100 * d:+.1f} points ({-100 * hi:+.1f} to {-100 * lo:+.1f})")
    hooks = [rows[(s, "B", "compact")] for s in sessions]
    S["hooks"] = {"note_delivered": sum(h.get("hook_note_in_transcript", False) for h in hooks),
                  "errors": sum(h.get("hook_errors", False) for h in hooks),
                  "pages": [h["archive"].get("pages") for h in hooks],
                  "image_tokens": [h["archive"].get("image_tokens") for h in hooks],
                  "render_seconds": [h["archive"].get("seconds") for h in hooks],
                  "archive_opened": sum(any(rows[(s, "B", t)].get("archive_reads", 0) for t in
                                            ("turn1", "turn2", "turn3", "turn4", "task")) for s in sessions)}
    h = S["hooks"]
    L += ["", f"Hooks: note in the post-compaction context in {h['note_delivered']}/{len(sessions)} sessions, "
          f"errors in {h['errors']}, archive opened in {h['archive_opened']}/{len(sessions)}; archives of "
          f"{min(h['pages'])}-{max(h['pages'])} pages ({min(h['image_tokens']):,}-{max(h['image_tokens']):,} image "
          f"tokens), rendered in {min(h['render_seconds'])}-{max(h['render_seconds'])} s."]
    A, B, D = (S["arms"][x] for x in "ABD")
    v = [("1. A loses >= 30 points vs D (pooled)", D["acc"] - A["acc"] >= 0.30, f"{100 * (A['acc'] - D['acc']):+.1f}"),
         ("2a. B within 5 points of D (pooled)", abs(B["acc"] - D["acc"]) <= 0.05, f"{100 * (B['acc'] - D['acc']):+.1f}"),
         ("2b. B within 10 points of D in each kind", all(abs(B["by_kind"][k] - D["by_kind"][k]) <= 0.10
                                                          for k in B["by_kind"]),
          ", ".join(f"{k} {100 * (B['by_kind'][k] - D['by_kind'][k]):+.1f}" for k in B["by_kind"])),
         ("3. B at most half of A per correct answer", B["cost_per_correct"] <= 0.5 * A["cost_per_correct"],
          f"${B['cost_per_correct']:.4f} vs ${A['cost_per_correct']:.4f} "
          f"({A['cost_per_correct'] / B['cost_per_correct']:.2f}x)"),
         ("4. hooks work unaided in every B session", h["note_delivered"] == len(sessions) and
          h["archive_opened"] == len(sessions), f"{h['note_delivered']}/{len(sessions)} notes, "
                                                 f"{h['archive_opened']}/{len(sessions)} opened"),
         ("5. task items: B beats A by >= 30 points", B["task"] - A["task"] >= 0.30,
          f"{100 * (B['task'] - A['task']):+.1f}")]
    S["verdicts"] = {n: {"pass": ok, "value": val} for n, ok, val in v}
    L += ["", "Pre-registered verdicts:", ""] + [f"* {n}: **{'PASS' if ok else 'FAIL'}** ({val})" for n, ok, val in v]
    fix = {(s, p["id"], p["kind"]): p["correct"] for (s, a, t), r in rows.items() if a == "Bfix"
           and (t.startswith("turn")) for p in r["scores"]}
    fix_task = {(s, p["id"]): p["correct"] for (s, a, t), r in rows.items() if a == "Bfix" and t == "task"
                for p in r["scores"]}
    fs = sorted({k[0] for k in fix})
    if fs and all((s, "Bfix", "task") in rows for s in fs):
        ck = [k for k in keys if k[0] in fs]
        comb = {k: (fix[k] if k in fix else per["B"][k]) for k in keys}
        pairs = [("q", per["D"][k], comb[k]) for k in keys]
        d, lo, hi = paired_diff_ci(pairs)
        _, _, p = mcnemar([t for _, t, _ in pairs], [i for _, _, i in pairs])
        S["post_hoc_fix"] = {"sessions": fs, "code_acc_B": acc("B", ck), "code_acc_Bfix": st.mean(fix[k] for k in ck),
                             "code_acc_D": acc("D", ck), "pooled_acc": st.mean(comb.values()),
                             "pooled_vs_D": {"diff": -d, "lo": -hi, "hi": -lo, "p": p},
                             "task_Bfix": st.mean(fix_task.values()),
                             "answer_cost_Bfix": sum(rows[(s, "Bfix", t)]["cost"] for s in fs
                                                     for t in ("turn1", "turn2", "turn3", "turn4", "task"))}
        x = S["post_hoc_fix"]
        L += ["", "## Post hoc (not pre-registered): the hook bug and the fixed hook", "",
              "10 of B's 14 misses were `def`-line questions on 7 files the Python minifier refused (they contain its "
              "own marker characters § and »). For those files the first hook fell back to flowed text and dropped "
              "the line numbers. The fixed hook keeps a §n tag on every line in that fallback. Arm `Bfix` repeats B on "
              f"the {len(fs)} code sessions (new fork, new compaction, same questions):", "",
              f"* code questions: D {100 * x['code_acc_D']:.1f}%, B {100 * x['code_acc_B']:.1f}%, "
              f"Bfix {100 * x['code_acc_Bfix']:.1f}%; task items {100 * x['task_Bfix']:.0f}%; answering "
              f"${x['answer_cost_Bfix']:.2f} for {len(fs)} sessions",
              f"* all 360 questions with Bfix for the code sessions: {100 * x['pooled_acc']:.1f}%, vs D "
              f"{-100 * d:+.1f} points ({-100 * hi:+.1f} to {-100 * lo:+.1f}), p = {p:.2g}"]
    (OUT / "summary.md").write_text("\n".join(L) + "\n")
    (OUT / "summary.json").write_text(json.dumps(S, indent=1, default=str))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
