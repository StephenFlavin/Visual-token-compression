"""EnterpriseRAG-Bench analysis -> results/erb/summary.md / summary.json (docs/claude/ERB_PLAN.md).

Per arm, on the questions every listed arm has judged: the leaderboard's overall score (mean of correct x fact
completeness), correctness, completeness, document recall; paired correctness difference against T10 (Newcombe 95%
interval, exact McNemar); answer-call cost at Opus 5.5 list prices and context tokens (input minus the same question's
`closed` input). Judge calibration: our judge's verdicts on the official baseline's answers (official_bm25) against
Onyx's published per-question scores (results_bm25.json): agreement on correctness and the mean difference.
"""
from __future__ import annotations

import json
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import erb_common as E  # noqa: E402

sys.path.insert(0, str(E.ROOT / "experiments"))
from analyse_claude_qa import mcnemar, paired_diff_ci  # noqa: E402
from run_erb import ARMS, RUNS, cost  # noqa: E402

J = E.OUT / "judge"


def judged(name: str) -> dict[str, dict]:
    p = J / f"results_{name}.json"
    return {r["question_id"]: r for r in json.loads(p.read_text())["questions"]} if p.exists() else {}


def overall(R: list[dict]) -> float:
    return st.mean((100.0 if r["answer_correct"] else 0.0) * r["completeness_pct"] / 100 for r in R)


def main() -> int:
    runs = {}
    if RUNS.exists():
        for r in map(json.loads, RUNS.read_text().splitlines()):
            runs[(r["question_id"], r["arm"])] = r
    res = {a: judged(a) for a in ARMS}
    arms = [a for a in ARMS if res[a]]
    L, S = ["# EnterpriseRAG-Bench: Opus 5.5, text vs page images", "",
            "Generated by `experiments/erb/analyse_erb.py`. Provisional judge (docs/claude/ERB_PLAN.md); the leaderboard "
            "re-judges submissions itself.", ""], {}
    off = {r["question_id"]: r for r in json.loads((E.LB / "results_bm25.json").read_text())["questions"]}
    cal = judged("official_bm25")
    if cal:
        qs = sorted(set(cal) & set(off))
        agree = sum(cal[q]["answer_correct"] == off[q]["answer_correct"] for q in qs) / len(qs)
        S["calibration"] = {"n": len(qs), "agreement": agree,
                            "ours_correct": st.mean(cal[q]["answer_correct"] for q in qs),
                            "onyx_correct": st.mean(off[q]["answer_correct"] for q in qs),
                            "ours_overall": overall([cal[q] for q in qs]), "onyx_overall": overall([off[q] for q in qs])}
        c = S["calibration"]
        L += ["## Judge calibration (GPT-5.4's published BM25 answers)", "",
              f"{c['n']} questions: our judge agrees with Onyx's correctness verdict on {100 * agree:.1f}%; correct "
              f"{100 * c['ours_correct']:.1f}% (ours) vs {100 * c['onyx_correct']:.1f}% (Onyx); overall "
              f"{c['ours_overall']:.1f} vs {c['onyx_overall']:.1f}.", ""]
    if arms:
        qs = sorted(set.intersection(*(set(res[a]) for a in arms)))
        L += [f"## Arms ({len(qs)} questions judged in every arm)", "",
              "| arm | docs | pages | overall | correct | completeness | recall | correct vs T10 (95% CI), p | "
              "context tokens | $ per answer |", "|---|---|---|---|---|---|---|---|---|---|"]
        for a in arms:
            R = [res[a][q] for q in qs]
            rr = [runs.get((q, a)) for q in qs]
            ctx = [r["input_tokens"] - runs[(q, "closed")]["input_tokens"] for q, r in zip(qs, rr)
                   if r and (q, "closed") in runs]
            if a == "T10" or "T10" not in arms:
                cmp = "(reference)"
            else:
                pairs = [("erb", res["T10"][q]["answer_correct"], res[a][q]["answer_correct"]) for q in qs]
                d, lo, hi = paired_diff_ci(pairs)
                _, _, p = mcnemar([t for _, t, _ in pairs], [i for _, _, i in pairs])
                cmp = f"{-100 * d:+.1f} ({-100 * hi:+.1f} to {-100 * lo:+.1f}), p={p:.2g}"
            x = {"n": len(R), "overall": overall(R), "correct": st.mean(r["answer_correct"] for r in R),
                 "completeness": st.mean(r["completeness_pct"] for r in R),
                 "recall": st.mean(r["document_recall_pct"] for r in R if r.get("document_recall_pct") is not None)
                 if any(r.get("document_recall_pct") is not None for r in R) else None,
                 "docs": st.mean(r["n_docs"] for r in rr if r) if any(rr) else None,
                 "pages": st.mean(r["n_pages"] for r in rr if r) if any(rr) else None,
                 "context_tokens": st.mean(ctx) if ctx else None,
                 "cost": st.mean(r["cost_list"] for r in rr if r) if any(rr) else None, "vs_T10": cmp}
            S[a] = x
            f = lambda v, fmt: "-" if v is None else format(v, fmt)  # noqa: E731
            L.append(f"| {a} | {f(x['docs'], '.1f')} | {f(x['pages'], '.1f')} | {x['overall']:.1f} | "
                     f"{100 * x['correct']:.1f}% | {x['completeness']:.1f}% | {f(x['recall'], '.1f')} | {cmp} | "
                     f"{f(x['context_tokens'], ',.0f')} | {f(x['cost'], '.4f')} |")
    use = J / "usage.jsonl"
    if use.exists():
        U = [json.loads(l) for l in use.read_text().splitlines()]
        S["judge_cost"] = sum(cost(u.get("usage") or {}) for u in U if not u.get("cached"))
        L += ["", f"Judge: {len(U)} calls, list-price estimate at Opus rates ${S['judge_cost']:.2f} (CLI-reported: "
              f"${sum(u.get('cost_usd') or 0 for u in U if not u.get('cached')):.2f})."]
    (E.OUT / "summary.md").write_text("\n".join(L) + "\n")
    (E.OUT / "summary.json").write_text(json.dumps(S, indent=1))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
