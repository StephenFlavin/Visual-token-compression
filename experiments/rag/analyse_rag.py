"""Analysis of results/rag/runs.jsonl -> results/rag/summary.md / summary.json.

Per dataset and arm: accuracy (exact match; F1 too), paired difference against T5 (Newcombe 95% interval, exact
McNemar), recall of the gold evidence in the passages the arm used, cost per call from its usage at Opus 5.5 list
prices, context tokens (the call's input minus the same question's closed-book input: what the passages cost,
without the CLI's fixed prompt), and cost per correct answer.
"""
from __future__ import annotations

import json
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments"))
from analyse_claude_qa import mcnemar, paired_diff_ci, wilson  # noqa: E402

OUT = ROOT / "results" / "rag"
ARMS = ["closed", "T5", "P5", "Pmatch", "T15", "hybrid"]
LABEL = {"closed": "no retrieval", "T5": "top-5 as text", "P5": "top-5 as pages", "Pmatch": "budget-matched pages",
         "T15": "top-15 as text", "hybrid": "top-3 text + pages"}


def cost(u: dict) -> float:
    return (u.get("input_tokens", 0) * 4 + u.get("output_tokens", 0) * 20 + u.get("cache_creation_input_tokens", 0) * 5
            + u.get("cache_read_input_tokens", 0) * 0.2) / 1e6


def main() -> int:
    rows = {}
    for l in (OUT / "runs.jsonl").read_text().splitlines():
        r = json.loads(l)
        rows[(r["dataset"], r["qid"], r["arm"])] = r                # a later row (re-run) wins
    by = defaultdict(dict)
    for (ds, q, arm), r in rows.items():
        by[(ds, q)][arm] = r
    L, J = ["# RAG with page images: results", "", "Generated by `experiments/rag/analyse_rag.py`.", ""], {}
    for ds in ("planted", "multihop", "hotpot"):
        qs = [q for (d, q) in by if d == ds and all(a in by[(d, q)] for a in ARMS)]
        if not qs:
            continue
        L += [f"## {ds} ({len(qs)} questions with all arms)", "",
              "| arm | passages | recall of evidence | accuracy (EM) | F1 | vs top-5 text (95% CI), p | context tokens | $ per question | $ per correct |",
              "|---|---|---|---|---|---|---|---|---|"]
        J[ds] = {}
        for arm in ARMS:
            R = [by[(ds, q)][arm] for q in qs]
            ok = sum(bool(r["em"]) for r in R)
            ctx = [r["input_tokens"] - by[(ds, q)]["closed"]["input_tokens"] for q, r in zip(qs, R)]
            c = [cost(r["usage"]) for r in R]
            if arm == "T5":
                cmp = "(reference)"
            else:
                pairs = [(ds, by[(ds, q)]["T5"]["em"], by[(ds, q)][arm]["em"]) for q in qs]
                d, lo, hi = paired_diff_ci(pairs)
                _, _, p = mcnemar([t for _, t, _ in pairs], [i for _, _, i in pairs])
                cmp = f"{-100 * d:+.1f} ({-100 * hi:+.1f} to {-100 * lo:+.1f}), p={p:.2g}"
            J[ds][arm] = {"n": len(R), "em": ok / len(R), "em_ci": wilson(ok, len(R)), "f1": st.mean(r["f1"] for r in R),
                          "passages": st.mean(r["n_passages"] for r in R), "recall": st.mean(r["recall_used"] for r in R),
                          "context_tokens": st.mean(ctx), "cost_per_q": st.mean(c), "cost_per_correct": sum(c) / max(1, ok),
                          "vs_T5": cmp}
            x = J[ds][arm]
            L.append(f"| {LABEL[arm]} | {x['passages']:.1f} | {x['recall']:.2f} | {100 * x['em']:.1f}% | {x['f1']:.3f} | "
                     f"{cmp} | {x['context_tokens']:,.0f} | ${x['cost_per_q']:.4f} | ${x['cost_per_correct']:.4f} |")
        types = sorted({by[(ds, q)]["T5"]["type"] for q in qs})
        L += ["", "Accuracy by question type:", "", "| type | n | " + " | ".join(LABEL[a] for a in ARMS) + " |",
              "|---|---|" + "---|" * len(ARMS)]
        for t in types:
            tq = [q for q in qs if by[(ds, q)]["T5"]["type"] == t]
            L.append(f"| {t} | {len(tq)} | " + " | ".join(
                f"{100 * sum(bool(by[(ds, q)][a]['em']) for q in tq) / len(tq):.0f}%" for a in ARMS) + " |")
        L.append("")
    (OUT / "summary.md").write_text("\n".join(L) + "\n")
    (OUT / "summary.json").write_text(json.dumps(J, indent=1))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
